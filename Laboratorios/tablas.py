
# Laboratorio 2 - Tablas de verdad
# Paso 1: Operadores relacionales

a = 10
b = 5

print("=== OPERADORES RELACIONALES (a = 10, b = 5) ===")
print("a == b ->", a == b)
print("a != b ->", a != b)
print("a > b  ->", a > b)
print("a < b  ->", a < b)
print("a >= b ->", a >= b)
print("a <= b ->", a <= b)

# Paso 2: Tabla de verdad del operador AND

print("\n=== TABLA DE VERDAD AND ===")
print("True  and True  ->", True and True)
print("True  and False ->", True and False)
print("False and True  ->", False and True)
print("False and False ->", False and False)

# Paso 3: Tabla de verdad del operador OR

print("\n=== TABLA DE VERDAD OR ===")
print("True  or True  ->", True or True)
print("True  or False ->", True or False)
print("False or True  ->", False or True)
print("False or False ->", False or False)
# Paso 4: Tabla de verdad del operador NOT

print("\n=== TABLA DE VERDAD NOT ===")
print("not True  ->", not True)
print("not False ->", not False)