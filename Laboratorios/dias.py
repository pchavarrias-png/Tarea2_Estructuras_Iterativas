
# Laboratorio 2 - Clasificador de dias

dia = int(input("Ingrese un numero del 1 al 7: "))

match dia:
    case 1:
        print("Lunes")
    case 2:
        print("Martes")
    case 3:
        print("Miercoles")
    case 4:
        print("Jueves")
    case 5:
        print("Viernes")
    case 6 | 7:
        print("Fin de semana")
    case _:
        print("Numero no valido")
